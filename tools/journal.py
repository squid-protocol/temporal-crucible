"""The experiment journal: dated entries under docs/journal/, one per study or finding.

    python tools/journal.py build   # regenerate the index in docs/journal/README.md and the take-homes list in docs/TAKEHOMES.md
    python tools/journal.py check   # validate every entry and fail if a generated section is stale (CI runs this)
    python tools/journal.py new --date 2026-11-08 --slug my-study --title "..."   # start an entry from the template

An entry is docs/journal/YYYY-MM-DD-<slug>.md with a header block between `---` lines (`key: value`, one per line)
followed by the write-up. Stdlib only, like every tool here.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
JDIR = ROOT / "docs" / "journal"
INDEX = JDIR / "README.md"
TAKE = ROOT / "docs" / "TAKEHOMES.md"
REGISTER = ROOT / "docs" / "HYPOTHESES.md"
TEMPLATE = JDIR / "_template.md"

REQUIRED = ("date", "title", "type", "status", "verdict", "theme", "takehome")
TYPES = ("confirmatory", "exploratory", "engine-finding", "program")
STATUSES = ("draft", "registered", "scored", "superseded")
VERDICTS = ("supported", "replicated", "mixed", "not-supported", "inconclusive", "pending", "n/a")
THEMES = {
    "provenance": "Identity, copies and provenance",
    "coupling": "Where the outside world touches code",
    "natural-history": "How code lives: natural history and regimes",
    "defect-prediction": "Predicting fixes, regressions and CVEs",
    "keyword-grammar": "The keyword grammar of functions",
    "fingerprints": "Function fingerprints and the shape lattice",
    "comments": "What comments say",
    "engine": "Engine findings (GitGalaxy itself)",
    "program": "The program and its methods",
}
MARK = ("<!-- journal:begin (generated by tools/journal.py build; do not edit by hand) -->", "<!-- journal:end -->")
NAME = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9-]+\.md$")
SECTIONS = ("## Question", "## What we did", "## What we found", "## Take-home", "## What it changed")


def parse(path: pathlib.Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("missing the --- header block")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        k, sep, v = line.partition(":")
        if not sep:
            raise ValueError(f"header line without ':': {line!r}")
        meta[k.strip()] = v.strip()
    meta["_path"] = path
    meta["_body"] = text[m.end():]
    return meta


def entries() -> list[dict]:
    return sorted((parse(p) for p in JDIR.glob("*.md") if NAME.match(p.name)), key=lambda e: (e["date"], e["_path"].name))


def split(v: str) -> list[str]:
    return [x.strip() for x in v.split(";") if x.strip()] if v else []


def render_index(es: list[dict]) -> str:
    rows = ["| date | entry | type | status | verdict | register ids | take-home |", "|---|---|---|---|---|---|---|"]
    for e in reversed(es):
        rows.append(f"| {e['date']} | [{e['title']}]({e['_path'].name}) | {e['type']} | {e['status']} | {e['verdict']} | "
                    f"{', '.join(split(e.get('ids', ''))) or '—'} | {e['takehome']} |")
    return "\n".join(rows)


def render_takehomes(es: list[dict]) -> str:
    out = []
    for key, title in THEMES.items():
        mine = [e for e in es if e["theme"] == key]
        if not mine:
            continue
        out += [f"### {title}", ""]
        for e in reversed(mine):
            level = e["type"] if e["verdict"] == "n/a" else e["verdict"]
            out.append(f"- **{e['takehome']}** — {level}, {e['date']} · [journal](journal/{e['_path'].name})")
        out.append("")
    return "\n".join(out).rstrip()


def splice(path: pathlib.Path, body: str) -> str:
    text = path.read_text(encoding="utf-8")
    a, b = text.index(MARK[0]), text.index(MARK[1])
    return text[: a + len(MARK[0])] + "\n\n" + body + "\n\n" + text[b:]


def check(es: list[dict]) -> list[str]:
    errs = []
    register = REGISTER.read_text(encoding="utf-8")
    for p in JDIR.glob("*.md"):
        if p.name not in ("README.md", "_template.md") and not NAME.match(p.name):
            errs.append(f"{p.name}: entry files are named YYYY-MM-DD-<slug>.md")
    for e in es:
        n = e["_path"].name
        for k in REQUIRED:
            if not e.get(k):
                errs.append(f"{n}: missing header field '{k}'")
        if not n.startswith(e.get("date", "") + "-"):
            errs.append(f"{n}: file name must start with its date ({e.get('date')})")
        for k, allowed in (("type", TYPES), ("status", STATUSES), ("verdict", VERDICTS), ("theme", tuple(THEMES))):
            if e.get(k) and e[k] not in allowed:
                errs.append(f"{n}: {k} '{e[k]}' not one of {', '.join(allowed)}")
        for i in split(e.get("ids", "")):
            if f"| {i} |" not in register and i not in register:
                errs.append(f"{n}: register id '{i}' not found in docs/HYPOTHESES.md")
        for d in split(e.get("docs", "")):
            if not (ROOT / d).exists():
                errs.append(f"{n}: linked doc '{d}' does not exist")
        if e.get("type") == "confirmatory" and e.get("status") in ("registered", "scored") and not split(e.get("ids", "")):
            errs.append(f"{n}: a confirmatory entry must cite its register ids")
        if e.get("status") == "draft" and e.get("verdict") not in ("pending", "n/a"):
            errs.append(f"{n}: a draft cannot carry a verdict")
        for s in SECTIONS:
            if s not in e["_body"]:
                errs.append(f"{n}: missing section '{s}'")
    if INDEX.read_text(encoding="utf-8") != splice(INDEX, render_index(es)):
        errs.append("docs/journal/README.md index is stale: run python tools/journal.py build")
    if TAKE.read_text(encoding="utf-8") != splice(TAKE, render_takehomes(es)):
        errs.append("docs/TAKEHOMES.md take-home list is stale: run python tools/journal.py build")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    sub.add_parser("check")
    nw = sub.add_parser("new")
    nw.add_argument("--date", required=True)
    nw.add_argument("--slug", required=True)
    nw.add_argument("--title", required=True)
    a = ap.parse_args()
    if a.cmd == "new":
        p = JDIR / f"{a.date}-{a.slug}.md"
        if p.exists():
            print(f"{p} exists", file=sys.stderr)
            return 1
        t = TEMPLATE.read_text(encoding="utf-8").replace("YYYY-MM-DD", a.date).replace("<title>", a.title)
        p.write_text(t, encoding="utf-8")
        print(f"created {p.relative_to(ROOT)}; fill it in, then run: python tools/journal.py build")
        return 0
    es = entries()
    if a.cmd == "build":
        INDEX.write_text(splice(INDEX, render_index(es)), encoding="utf-8")
        TAKE.write_text(splice(TAKE, render_takehomes(es)), encoding="utf-8")
        print(f"journal: {len(es)} entries; index and take-homes rebuilt")
        return 0
    errs = check(es)
    for x in errs:
        print("ERROR", x)
    print(f"journal check: {len(es)} entries, {len(errs)} problem(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    raise SystemExit(main())
